'use strict'
// Session windows, key routing, closing projects, undo and the team form on the real app, with real shells. Claude
// windows run fake-claude.cjs, so this uses no quota. Process ids are asked of the shells themselves.
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const L = require('./lib.cjs')
const U = require('./uilib.cjs')
const { rightClickCanvas } = require('./scenes.cjs')

const c = L.checker()
U.watchdog(6 * 60_000)
let currentPage = null
/** On a failure, what the main terminal shows and where the keyboard is, so the cause can be read from the run. */
const step = U.stepper(c.check, async () => {
  if (!currentPage) return
  const tail = (await L.snapshot(currentPage, 'term').catch(() => '')).slice(-600)
  const focus = await currentPage.evaluate(() => {
    const a = document.activeElement
    return { tag: a?.tagName, cls: a?.className, node: a?.closest?.('.react-flow__node')?.dataset.id }
  }).catch(() => null)
  console.log('  terminal tail:', JSON.stringify(tail))
  console.log('  keyboard at:', JSON.stringify(focus))
})
const titleLog = path.join(os.tmpdir(), `patchbay-title-${process.pid}.json`)

async function main() {
  const { profile } = U.seeded('ui-windows')
  let app = await L.launch({ profile, env: { FAKE_TITLE_LOG: titleLog } })
  let page = app.page
  currentPage = page
  const tool = (id, name) => `${U.nodeSel(id)} [data-tool="${name}"]`
  try {
    await L.waitFor('the shell', async () => /\$/.test(await L.snapshot(page, 'term')), 20000)
    await L.fitView(page)
    // Fitting resizes every terminal, and Git Bash can drop a key sent just after that, even one that never went
    // through the app's key handling. Hearing from the shell first keeps that apart from what's being checked below.
    await L.sleep(2000)
    await U.shellPid(page, 'term', 'ready')

    await step('keys reach a focused terminal', async () => {
      await U.focusTerminal(page, 'term')
      await U.typeLine(page, 'echo typed-$((40+2))')
      await L.waitFor('typed text to come back', async () => (await L.snapshot(page, 'term')).includes('typed-42'), 8000)
      c.check('Typing reaches the terminal', true)
      await U.typeLine(page, 'sleep 60; echo sleep-$((3+4))x')
      await L.sleep(500)
      await U.chord(page, 'ctrl', 'KeyC')
      await L.sleep(500)
      await U.typeLine(page, 'echo after-$((1+1))')
      await L.waitFor('the shell to answer after Ctrl+C', async () => (await L.snapshot(page, 'term')).includes('after-2'), 8000)
      c.check('Ctrl+C reaches the shell and stops the program', !(await L.snapshot(page, 'term')).includes('sleep-7x'))
      await page.keyboard.type('xyz')
      await U.chord(page, 'ctrl', 'KeyA')
      await U.typeLine(page, 'echo moved-')
      await L.waitFor('Ctrl+A to act on the line', async () => (await L.snapshot(page, 'term')).includes('moved-xyz'), 5000).catch(() => {})
      c.check('Ctrl+A reaches the terminal and does not select nodes', (await L.snapshot(page, 'term')).includes('moved-xyz') && (await page.$$('.react-flow__node.selected')).length <= 1)
      const beforeUndo = (await L.doc(page)).nodes.length
      await U.chord(page, 'ctrl', 'KeyZ')
      await L.sleep(300)
      c.check('Ctrl+Z goes to the terminal, not to undo', (await L.doc(page)).nodes.length === beforeUndo)
      await U.typeLine(page, 'fg 2>/dev/null; true')
      await U.chord(page, 'ctrl', 'KeyF')
      c.check('Ctrl+F opens the find bar', !!(await page.$(`${U.nodeSel('term')} .find`)))
      await page.keyboard.press('Escape')
      await L.sleep(100)
      await page.evaluate(() => navigator.clipboard.writeText('echo pasted-$((2+2))'))
      await U.focusTerminal(page, 'term')
      await U.chord(page, 'ctrl', 'KeyV')
      await page.keyboard.press('Enter')
      await L.waitFor('the paste', async () => (await L.snapshot(page, 'term')).includes('pasted-4'), 5000)
      c.check('Ctrl+V pastes into the terminal', true)
      // Nothing is to the right of this one, so that key stays put.
      await U.chord(page, 'ctrl+shift', 'ArrowRight')
      const moved = await page.evaluate(() => document.activeElement?.closest('.react-flow__node')?.dataset.id)
      await U.chord(page, 'ctrl+shift', 'ArrowLeft')
      const movedBack = await page.evaluate(() => document.activeElement?.closest('.react-flow__node')?.dataset.id)
      c.check('Ctrl+Shift+arrows move between windows', moved === 'term' && movedBack === 'idle', { moved, movedBack })
    })

    await step('refresh', async () => {
      const before = await U.shellPid(page, 'term', 'a')
      await L.waitFor('that to be on screen', async () => (await L.screen(page, 'term')).join('\n').includes(`pid-a-${before}`), 5000)
      await page.click(tool('term', 'refresh'))
      await L.sleep(800)
      c.check('Refresh draws the output again', (await L.screen(page, 'term')).join('\n').includes(`pid-a-${before}`))
      const after = await U.shellPid(page, 'term', 'b')
      c.check('Refresh keeps the same process', before === after, { before, after })
      const box = await page.$(`${U.nodeSel('term')} .xterm`)
      c.check('The view is live afterwards', !!box)
      // Asks the terminal to identify itself. The answer arrives at the prompt, where it shows, so counting those tells
      // whether a rebuilt view answered the old question a second time.
      await L.input(page, 'term', "printf '\\033[c'; echo asked-$((2+3))\r")
      await L.waitFor('the question to be answered', async () => /;42c/.test(await L.snapshot(page, 'term')), 5000)
      await L.input(page, 'term', '\x15')
      await L.sleep(300)
      const answers = async () => ((await L.snapshot(page, 'term')).match(/;42c/g) ?? []).length
      const once = await answers()
      await page.click(tool('term', 'refresh'))
      await L.sleep(1200)
      c.check('Refresh sends nothing into the session', (await answers()) === once, { once, now: await answers() })
    })

    await step('find button', async () => {
      await page.click(tool('term', 'find'))
      await L.sleep(100)
      c.check('Find opens the find bar', !!(await page.$(`${U.nodeSel('term')} .find`)))
      await page.keyboard.press('Escape')
    })

    await step('dragging', async () => {
      const before = await L.nodeOf(page, 'term')
      const head = await (await page.$(tool('term', 'maximize'))).boundingBox()
      await page.mouse.move(head.x + 5, head.y + 5)
      await page.mouse.down()
      await page.mouse.move(head.x + 60, head.y + 60, { steps: 4 })
      await page.mouse.up()
      await L.sleep(300)
      const after = await L.nodeOf(page, 'term')
      c.check('Pressing a tool button does not drag the window', after.x === before.x && after.y === before.y)
    })

    await step('maximize', async () => {
      const before = await L.nodeOf(page, 'term')
      const sizeBefore = await U.ptySize(page, 'term', 'c')
      const pid = await U.shellPid(page, 'term', 'd')
      await page.click(tool('term', 'maximize'))
      await L.waitFor('it to fill the canvas', () => page.$('.unit-maximized'), 3000, 50)
      await L.sleep(500)
      const stage = await page.$eval('.stage', (s) => s.getBoundingClientRect().height)
      const box = await page.$eval('.unit-maximized', (u) => u.getBoundingClientRect().height)
      c.check('Maximize fills the canvas area', box > stage * 0.9, { box, stage })
      await L.shot(page, 'ui-after-maximized-run')
      const sizeBig = await U.ptySize(page, 'term', 'e')
      c.check('The terminal refits', sizeBig !== sizeBefore, { sizeBefore, sizeBig })
      c.check('The session is the same one', (await U.shellPid(page, 'term', 'f')) === pid)
      await page.keyboard.press('Escape')
      await L.sleep(300)
      c.check('Esc restores it', !(await page.$('.unit-maximized')))
      const after = await L.nodeOf(page, 'term')
      c.check('The saved layout did not change', after.x === before.x && after.y === before.y && after.width === before.width && after.height === before.height)
      await page.click(tool('term', 'maximize'))
      await L.waitFor('it to fill again', () => page.$('.unit-maximized'), 3000, 50)
      await page.click('.unit-maximized .xterm-screen')
      await L.sleep(100)
      await page.keyboard.press('Escape')
      await L.sleep(200)
      c.check('With the terminal in use, Esc stays with the terminal', !!(await page.$('.unit-maximized')))
      // Esc reached the shell, which then takes the next key as part of it, so this clears that.
      await L.input(page, 'term', '\x03')
      await U.chord(page, '', 'F11')
      c.check('F11 restores it from there', !(await page.$('.unit-maximized')))
      await page.click(tool('term', 'maximize'))
      await L.waitFor('it to fill a third time', () => page.$('.unit-maximized'), 3000, 50)
      await page.click('.unit-maximized [data-tool="maximize"]')
      await L.sleep(200)
      c.check('The same button restores it', !(await page.$('.unit-maximized')))
      await L.sleep(500)
      const sizeBack = await U.ptySize(page, 'term', 'g')
      c.check('The terminal fits its window again', sizeBack === sizeBefore, { sizeBefore, sizeBack })
    })

    await step('font size', async () => {
      const pid = await U.shellPid(page, 'term', 'h')
      const size = await U.ptySize(page, 'term', 'i')
      const other = await U.fontSizeOf(page, 'w-term').catch(() => U.fontSizeOf(page, 'run'))
      const start = await U.fontSizeOf(page, 'term')
      await page.click(tool('term', 'font-larger'))
      await page.click(tool('term', 'font-larger'))
      await page.click(tool('term', 'font-larger'))
      await L.waitFor('the new size', async () => (await U.fontSizeOf(page, 'term')) === start + 3, 3000, 50)
      c.check('Larger changes this window', true, { start, now: start + 3 })
      c.check('And not another one', (await U.fontSizeOf(page, 'run')) === other, { other })
      for (const id of ['idle', 'run']) {
        const was = await U.fontSizeOf(page, id)
        await page.click(tool(id, 'font-larger'))
        await L.waitFor(`${id} to change size`, async () => (await U.fontSizeOf(page, id)) === was + 1, 3000, 50)
        await page.click(tool(id, 'font-reset'))
        await L.waitFor(`${id} to change back`, async () => (await U.fontSizeOf(page, id)) === was, 3000, 50)
      }
      c.check('It works on Claude and run windows too', true)
      await L.sleep(300)
      const resized = await U.ptySize(page, 'term', 'j')
      c.check("The session's size follows", resized !== size, { size, resized })
      c.check('The process is the same', (await U.shellPid(page, 'term', 'k')) === pid)
      c.check('The toolbar shows the size', (await page.$eval(tool('term', 'font-reset'), (b) => b.textContent)) === String(start + 3))
      c.check('It is saved on the node, not the other', (await L.nodeOf(page, 'term')).fontSize === start + 3 && (await L.nodeOf(page, 'run')).fontSize === undefined)
      for (let i = 0; i < 12; i++) await page.$eval(tool('term', 'font-larger'), (b) => b.click())
      await L.sleep(200)
      c.check('It stops at the top of the range', (await L.nodeOf(page, 'term')).fontSize === 20)
      await page.click(tool('term', 'font-reset'))
      await L.sleep(200)
      c.check('Clicking the size goes back to the global size', (await L.nodeOf(page, 'term')).fontSize === undefined && (await U.fontSizeOf(page, 'term')) === start)
      await U.focusTerminal(page, 'term')
      await U.chord(page, 'ctrl+shift', 'Equal')
      await L.sleep(200)
      c.check('Ctrl+Shift+= works from inside the terminal', (await L.nodeOf(page, 'term')).fontSize === start + 1)
      await page.click(tool('term', 'font-larger'))
      await L.sleep(800)
    })

    await step('name with AI', async () => {
      await page.click(tool('term', 'name'))
      await L.waitFor('the title', async () => (await L.nodeOf(page, 'term')).title === 'Pretend title', 15000)
      const asked = JSON.parse(fs.readFileSync(titleLog, 'utf8'))
      c.check('Name with AI sets the title', true)
      c.check('It asked with no tools and no hooks, in a folder of its own', asked.safe && asked.args[asked.args.indexOf('--tools') + 1] === '' && asked.cwd.endsWith('naming'), asked.cwd)
      c.check('It passed the terminal output', /pid-[a-z]-\d+/.test(asked.input))
      await page.mouse.click(...Object.values(await U.emptySpot(page)))
      await U.chord(page, 'ctrl', 'KeyZ')
      await L.waitFor('the old title', async () => (await L.nodeOf(page, 'term')).title === 'Dev shell', 3000, 50)
      c.check('Undo takes the new title back', true)
      await L.openNode(page, L.terminal('fresh', (await L.nodeOf(page, 'term')).cwd, 40, 900, { command: undefined, projectId: 'p1' }))
      await L.sleep(1500)
      await L.input(page, 'fresh', 'echo fail-naming\r')
      await L.sleep(800)
      await page.$eval(tool('fresh', 'name'), (b) => b.click())
      await L.waitFor('the error', () => page.$(`${U.nodeSel('fresh')} [data-naming-error]`), 15000)
      c.check('A failure shows in plain words', /couldn't name it/.test(await page.$eval(`${U.nodeSel('fresh')} [data-naming-error]`, (e) => e.textContent)))
      await page.evaluate(() => window.patchbay.dispatch({ op: 'removeNodes', ids: ['fresh'], at: Date.now() }))
    })

    await step('canvas menu and team', async () => {
      await rightClickCanvas(page)
      await L.sleep(150)
      const items = await page.$$eval('.menu-panel .menu-item', (i) => i.map((x) => ({ id: x.dataset.cmd, icon: !!x.querySelector('svg') })))
      c.check('Every option in the canvas menu has an icon', items.length > 8 && items.every((i) => i.icon), items.filter((i) => !i.icon))
      c.check('It offers Spawn a team and a new trigger', items.some((i) => i.id === 'spawn-team') && items.some((i) => i.id === 'new-trigger'))
      const count = (await L.doc(page)).nodes.length
      await page.click('.menu-panel [data-cmd="spawn-team"]')
      await L.waitFor('the form', () => page.$('form[aria-label="New team"]'), 3000, 50)
      c.check('With no task it cannot start', await page.$eval('form[aria-label="New team"] .btn-solid', (b) => b.disabled))
      await page.type('[name="task"]', 'Tidy the docs folder')
      await page.click('form[aria-label="New team"] .btn-solid')
      const lead = await L.waitFor('the lead', async () => (await L.doc(page)).nodes.find((n) => n.title === 'Team lead'), 8000)
      c.check('It opens exactly one lead Claude', lead.kind === 'claude' && (await L.doc(page)).nodes.length === count + 1)
      const screen = await L.waitFor('the prompt to arrive', async () => {
        const s = await L.snapshot(page, lead.id)
        return s.includes('patchbay spawn-team') && s
      }, 8000)
      c.check('Its prompt holds the task and the plan', screen.includes('Tidy the docs folder'))
      await page.evaluate((id) => window.patchbay.dispatch({ op: 'removeNodes', ids: [id], at: Date.now() }), lead.id)
      await L.sleep(500)
    })

    await step('undo', async () => {
      const pane = await U.emptySpot(page)
      await page.mouse.click(pane.x, pane.y)
      const notes = async () => (await L.doc(page)).nodes.filter((n) => n.kind === 'sticky').length
      const before = await notes()
      await U.chord(page, 'ctrl+shift', 'KeyN')
      await L.waitFor('the note', async () => (await notes()) === before + 1, 3000, 50)
      await U.chord(page, 'ctrl', 'KeyZ')
      await L.waitFor('it to go', async () => (await notes()) === before, 3000, 50)
      c.check('Undo removes a new note', true)
      await U.chord(page, 'ctrl', 'KeyY')
      await L.waitFor('it to return', async () => (await notes()) === before + 1, 3000, 50)
      c.check('Redo brings it back', true)
      await U.chord(page, 'ctrl', 'KeyZ')
      const start = await L.nodeOf(page, 'run')
      const head = await (await page.$(`${U.nodeSel('run')} .unit-head .title`)).boundingBox()
      await page.mouse.move(head.x + 4, head.y + 4)
      await page.mouse.down()
      await page.mouse.move(head.x + 40, head.y + 30, { steps: 5 })
      await page.mouse.up()
      await L.waitFor('the move to save', async () => (await L.nodeOf(page, 'run')).x !== start.x, 3000, 50)
      await page.mouse.click(pane.x, pane.y)
      await U.chord(page, 'ctrl', 'KeyZ')
      await L.waitFor('it to move back', async () => (await L.nodeOf(page, 'run')).x === start.x, 3000, 50)
      c.check('Undo puts a moved window back', true)
      const pid = await U.shellPid(page, 'term', 'm')
      await U.chord(page, 'ctrl', 'KeyY')
      await U.chord(page, 'ctrl', 'KeyZ')
      c.check('Undo and redo leave processes alone', (await U.shellPid(page, 'term', 'n')) === pid)
      await page.evaluate(() => window.patchbay.dispatch({ op: 'removeNodes', ids: ['unk'], at: Date.now() }))
      await L.waitFor('it to close', async () => !(await L.nodeOf(page, 'unk')), 5000, 50)
      await U.chord(page, 'ctrl', 'KeyZ')
      await L.sleep(300)
      c.check('Closing a session is not undone', !(await L.nodeOf(page, 'unk')))
    })

    await step('closing a project', async () => {
      await page.evaluate(() => window.patchbay.dispatch({ op: 'switchProject', id: 'p2' }))
      await L.sleep(600)
      const pid = await U.shellPid(page, 'w-term', 'p')
      await (await page.$$('.project-tab'))[1].click({ button: 'right' })
      await L.sleep(150)
      await page.click('.menu-panel [data-cmd="close-project"]')
      await L.waitFor('the tab to go', async () => (await page.$$('.project-tab')).length === 1, 5000, 50)
      const doc = await L.doc(page)
      c.check('Closing hides the tab and shows the neighbor', doc.activeProjectId === 'p1')
      c.check('It keeps the nodes', doc.nodes.some((n) => n.id === 'w-term'))
      c.check('Its session keeps running', (await U.shellPid(page, 'w-term', 'q')) === pid)
      await page.click('[data-sidebar-tab="project"]')
      await L.sleep(150)
      c.check('It is listed as recently closed', !!(await page.$('[data-closed-project="p2"]')))
      await L.shot(page, 'ui-after-closed-project-run')
      await page.click('[data-closed-project="p2"]')
      await L.waitFor('it to come back', async () => (await U.active(page)) === 'p2', 5000, 50)
      await L.sleep(600)
      c.check('Reopening brings back the tab and its windows', (await page.$$('.project-tab')).length === 2 && (await U.shownNodes(page)).includes('w-term'))
      c.check('It is the same session', (await U.shellPid(page, 'w-term', 'r')) === pid)
      await (await page.$$('.project-tab'))[1].click({ button: 'right' })
      await L.sleep(150)
      await page.click('.menu-panel [data-cmd="delete-project"]')
      await L.sleep(100)
      const asked = await page.$eval('.menu-panel [data-cmd="delete-project"]', (b) => b.textContent)
      c.check('Deleting asks, naming what it ends', asked.includes('Site server') && asked.includes('Landing page') && /for good/.test(asked), asked)
      await L.shot(page, 'ui-after-delete-confirm-run')
      await page.click('.menu-panel [data-cmd="delete-project"]')
      await L.waitFor('it to go', async () => (await L.doc(page)).projects.length === 1, 10000, 100)
      c.check('Confirming deletes it', !(await L.doc(page)).nodes.some((n) => n.id === 'w-term'))
      await page.click('.project-tab', { button: 'right' })
      await L.sleep(150)
      c.check('The last project can be neither closed nor deleted', await page.$$eval('.menu-panel [data-cmd="close-project"], .menu-panel [data-cmd="delete-project"]', (b) => b.every((x) => x.disabled)))
      await page.keyboard.press('Escape')
    })

    await step('relaunch', async () => {
      const size = (await L.nodeOf(page, 'term')).fontSize
      await L.sleep(800)
      await app.quit().catch(() => app.forceKill())
      app = await L.launch({ profile, env: { FAKE_TITLE_LOG: titleLog } })
      page = app.page
      currentPage = page
      await L.sleep(2000)
      c.check('A window font size survives a restart', (await L.nodeOf(page, 'term')).fontSize === size && (await U.fontSizeOf(page, 'term')) === size, { size })
      c.check('A window with none follows the global size', (await U.fontSizeOf(page, 'run')) === 13)
    })

    c.check('No errors in the page', app.problems.length === 0, app.problems)
  } finally {
    await app.forceKill().catch(() => {})
    L.cleanup(profile)
    fs.rmSync(titleLog, { force: true })
  }
  c.finish()
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
