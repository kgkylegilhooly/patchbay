'use strict'
// The sidebar, palette and shortcuts on the real app, with real sessions. Its Claude windows run fake-claude.cjs, so
// this uses no quota. ui-real.cjs does the few checks that need the real thing.
const L = require('./lib.cjs')
const U = require('./uilib.cjs')

const c = L.checker()
U.watchdog(5 * 60_000)
const step = U.stepper(c.check)

async function main() {
  const { profile } = U.seeded('ui-sidebar')
  let app = await L.launch({ profile })
  let page = app.page
  try {
    await step('statuses', async () => {
      await L.waitFor('every status to settle', async () => {
        const s = await L.statuses(page)
        return s.needs === 'needs-you' && s.work === 'working' && s.idle === 'idle' && s.unk === 'unknown' && s['w-idle'] === 'idle'
      }, 30000)
      c.check('An old version 2 save loaded as version 3', (await L.doc(page)).version === 3)
    })

    await step('project tab', async () => {
      await page.click('[data-sidebar-tab="project"]')
      c.check('Project lists every project', (await page.$$('[data-project-section]')).length === 2)
      const here = await U.rowIds(page, '[data-project-section="p2"]')
      c.check('Sessions in the other project are listed', here.includes('w-term') && here.includes('w-idle'), here)
      c.check('A group section stays inside its project', await page.$eval('[data-project-section="p1"]', (s) => [...s.querySelectorAll('.sidebar-group')].some((g) => g.textContent.includes('Backend'))))
      // Usage is read from status lines once a second, so the pill can follow the status by a moment.
      const pill = await L.waitFor('the context pill', () => page.$eval('[data-project-section="p1"] [data-session="needs"]', (r) => !r.querySelector('.project-badge') && !r.querySelector('.session-where') && /71%/.test(r.querySelector('.session-context')?.textContent ?? '')), 5000).catch(() => false)
      c.check('Rows have a context pill, and no badge or folder repeating their project', pill)
      await page.click('[data-session="w-term"]')
      await L.waitFor('the other project to show', async () => (await U.active(page)) === 'p2', 5000, 50)
      await L.sleep(500)
      c.check('Clicking a session in another project switches to it', (await U.shownNodes(page)).includes('w-term'))
      const visible = await page.$eval(U.nodeSel('w-term'), (n) => {
        const r = n.getBoundingClientRect()
        return r.left >= 0 && r.top >= 0 && r.right <= innerWidth && r.bottom <= innerHeight
      })
      c.check('And it is centered in view', visible)
      await page.click('.project-tab')
      await L.sleep(400)
      await page.click('[data-section="project:p2"]')
      c.check('A project header collapses', (await U.rowIds(page, '[data-project-section="p2"]')).length === 0)
    })

    await step('status tab', async () => {
      await page.click('[data-sidebar-tab="status"]')
      await L.sleep(200)
      await page.evaluate(() => window.patchbay.markSeen('idle'))
      await page.evaluate(() => window.patchbay.markSeen('w-idle'))
      await L.sleep(300)
      const section = (id) => U.rowIds(page, `[data-status-section="${id}"]`)
      // The fake "unknown" agent ends its turn on an API error, so it waits on the person under Need attention.
      c.check('Need attention, with the agent stopped on an error', (await section('needs-you')).sort().join() === 'needs,unk', await section('needs-you'))
      c.check('Running', (await section('running')).join() === 'work', await section('running'))
      c.check('Idle has only the idle Claude sessions', (await section('idle')).sort().join() === 'idle,w-idle', await section('idle'))
      c.check('An empty No status yet section is left out', !(await page.$('[data-status-section="unknown"]')))
      const plain = await section('plain')
      c.check('Terminals and run commands get a section of their own, and never Idle', ['term', 'run', 'w-term'].every((x) => plain.includes(x)), plain)
      const counts = await page.$$eval('[data-status-section] .sidebar-section', (h) => h.map((x) => x.textContent))
      c.check('Each section shows a count', counts.some((t) => /Need attention\s*2/.test(t)) && counts.some((t) => /Idle\s*2/.test(t)), counts)
      c.check('Rows show their project badge', await page.$eval('[data-status-section="idle"] [data-session="w-idle"]', (r) => !!r.querySelector('.project-badge')))
      c.check('Rows show their project', await page.$eval('[data-status-section="idle"] [data-session="w-idle"] .session-project', (e) => e.textContent === 'Website'))
      c.check('Rows show time since last activity', await page.$eval('[data-status-section="idle"] [data-session="idle"] .session-time', (e) => /now|ago/.test(e.textContent)))
      await L.sleep(100)
      await page.type('.sidebar-filter', 'landing')
      await L.sleep(150)
      c.check('The filter works in Status', (await U.rowIds(page, '[data-status-section]')).join() === 'w-idle', await U.rowIds(page, '[data-status-section]'))
      await page.click('[data-sidebar-tab="project"]')
      await L.sleep(150)
      c.check('The filter works in Project', (await U.rowIds(page, '[data-project-section]')).join() === 'w-idle', await U.rowIds(page, '[data-project-section]'))
      await page.$eval('.sidebar-filter', (i) => i.select())
      await page.keyboard.press('Backspace')
      await L.shot(page, 'ui-after-sidebar-run')
    })

    await step('pin', async () => {
      await page.click('[data-sidebar="pin"]')
      const pane = await U.emptySpot(page)
      await page.mouse.click(pane.x, pane.y)
      await L.sleep(200)
      c.check('Unpinned, clicking the canvas hides the sidebar', !(await page.$('.sidebar')))
      await U.chord(page, 'ctrl+shift', 'KeyE')
      c.check('It comes back from its shortcut', !!(await page.$('.sidebar')))
      await page.click('[data-sidebar="pin"]')
      await page.mouse.click(pane.x, pane.y)
      await L.sleep(200)
      c.check('Pinned, it stays open', !!(await page.$('.sidebar')))
    })

    await step('recently closed', async () => {
      await page.click('[data-section="recent"]')
      await L.sleep(150)
      const rows = await page.$$eval('[data-closed-session]', (r) => r.map((x) => x.textContent))
      c.check('Closed conversations lists with relative times', rows.length === 2 && /Parser review.*40m ago/.test(rows[0]) && /Landing page copy.*1d ago/.test(rows[1]), rows)
      await page.click('[data-closed-session="closed-a"]')
      const back = await L.waitFor('it to reopen', async () => (await L.doc(page)).nodes.find((n) => n.title === 'Parser review'), 8000)
      c.check('Clicking one reopens it, the same as the Recent panel', !!back && !(await L.doc(page)).closed.some((x) => x.id === 'closed-a'))
    })

    await step('palette', async () => {
      const spot = await U.emptySpot(page)
      await page.mouse.click(spot.x, spot.y)
      await U.chord(page, 'ctrl', 'KeyK')
      c.check('Ctrl+K opens the palette', !!(await page.$('.palette')))
      const notes = async () => (await L.doc(page)).nodes.filter((n) => n.kind === 'sticky').length
      const before = await notes()
      await page.keyboard.type('new note')
      await L.sleep(100)
      await L.shot(page, 'ui-after-palette-run')
      await page.keyboard.press('Enter')
      await L.waitFor('the note', async () => (await notes()) === before + 1, 5000, 50)
      c.check('Enter runs the action', !(await page.$('.palette')))
      await U.chord(page, 'ctrl', 'KeyK')
      const first = await page.$eval('.palette-item', (i) => i.dataset.palette)
      c.check('Recent actions come first', first === 'new-sticky', first)
      await page.keyboard.press('ArrowDown')
      const second = await page.$eval('.palette-item-active', (i) => i.dataset.palette)
      c.check('Arrow keys move the choice', second !== first, second)
      await page.keyboard.press('Escape')
      await L.sleep(100)
      c.check('Esc closes it', !(await page.$('.palette')))
      await U.chord(page, 'ctrl', 'KeyK')
      await page.keyboard.type('Site server')
      await L.sleep(100)
      await page.keyboard.press('Enter')
      await L.waitFor('the project to change', async () => (await U.active(page)) === 'p2', 5000, 50)
      c.check('It jumps to a session in another project', true)
      await page.click('.project-tab')
      await L.sleep(400)
      await page.evaluate(() => [...document.querySelectorAll('.menubar-item')].find((b) => b.textContent === 'View').click())
      await L.sleep(100)
      await page.click('.menu-panel [data-cmd="open-palette"]')
      await L.sleep(150)
      c.check('It opens from the View menu', !!(await page.$('.palette')))
      await page.keyboard.press('Escape')
    })

    await step('rebinding', async () => {
      await U.chord(page, 'ctrl', 'Comma')
      c.check('Ctrl+, opens Settings', !!(await page.$('.settings')))
      await page.click('.set-nav-item[data-section="keys"]')
      await L.sleep(150)
      c.check('Every action is listed', (await page.$$('[data-action]')).length > 30)
      await page.click('[data-bind="tidy"]')
      await U.chord(page, 'ctrl', 'KeyC')
      c.check('Ctrl+C is refused', /can't be moved/.test(await page.$eval('.key-problem', (e) => e.textContent)))
      await page.click('[data-bind="tidy"]')
      await U.chord(page, 'ctrl', 'KeyR')
      c.check('A key terminals use gets a warning', /history/.test(await page.$eval('.key-warning', (e) => e.textContent)))
      await page.$$eval('.key-warning .btn', (b) => b[1].click())
      await page.click('[data-bind="tidy"]')
      await U.chord(page, 'ctrl+shift', 'KeyT')
      c.check('A key in use names the other action', /New terminal/.test(await page.$eval('.key-warning', (e) => e.textContent)))
      await page.$$eval('.key-warning .btn', (b) => b[1].click())
      await page.click('[data-bind="new-sticky"]')
      await U.chord(page, '', 'F9')
      c.check('The new key shows', (await page.$eval('[data-bind="new-sticky"]', (b) => b.textContent)) === 'F9')
      await page.keyboard.press('Escape')
      await L.sleep(200)
      const notes = async () => (await L.doc(page)).nodes.filter((n) => n.kind === 'sticky').length
      const before = await notes()
      await U.chord(page, '', 'F9')
      await L.waitFor('the rebound key to work', async () => (await notes()) === before + 1, 5000, 50)
      c.check('A rebound shortcut works', true)
      await U.chord(page, 'ctrl+shift', 'KeyN')
      await L.sleep(300)
      c.check('The old key no longer does', (await notes()) === before + 1)
    })

    await step('relaunch', async () => {
      // With a Claude window busy, quitting stops to ask. Closing them takes the ordinary route out, right after the change.
      await page.evaluate(() => window.patchbay.dispatch({ op: 'removeNodes', ids: ['needs', 'work'], at: Date.now() }))
      await L.waitFor('them to close', async () => !(await L.nodeOf(page, 'work')), 8000)
      const code = await app.quit()
      c.check('It quits cleanly', code === 0, code)
      app = await L.launch({ profile })
      page = app.page
      await L.sleep(1500)
      c.check('A collapsed project stays collapsed after a restart', (await U.rowIds(page, '[data-project-section="p2"]')).length === 0)
      const notes = async () => (await L.doc(page)).nodes.filter((n) => n.kind === 'sticky').length
      const before = await notes()
      await U.chord(page, '', 'F9')
      await L.waitFor('the saved key', async () => (await notes()) === before + 1, 5000, 50)
      c.check('A rebound shortcut survives a restart', true)
      await U.chord(page, 'ctrl', 'Comma')
      await page.click('.set-nav-item[data-section="keys"]')
      await L.sleep(100)
      await page.click('[data-reset-all]')
      c.check('Reset all gives the defaults back', (await page.$eval('[data-bind="new-sticky"]', (b) => b.textContent)) === 'Ctrl+Shift+N')
      await page.keyboard.press('Escape')
    })

    c.check('No errors in the page', app.problems.length === 0, app.problems)
  } finally {
    await app.forceKill().catch(() => {})
    L.cleanup(profile)
  }
  c.finish()
}

main().catch((e) => {
  console.error(e)
  process.exit(1)
})
